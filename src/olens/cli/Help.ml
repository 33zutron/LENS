(* coupling: keep the summaries for the login/scan/ci subcommands similar
   to what's printed by print_lens_dashdash_help. *)
let print_help () =
  (* TODO: add a Out.printf_color? *)
  Ocolor_format.printf
    {|
┌──── @{<green>○○○@} ────┐
│ Lens CLI │
└─────────────┘
Lens CLI scans your code for bugs, security and dependency vulnerabilities.

For more information about Lens, visit @{<cyan;ul>https://lens.dev@}

@{<ul>Get Started@}:
  Run @{<cyan>`lens login && lens ci`@} to enable Pro rules, Lens Supply Chain,
  and secrets scanning. Without logging in, Lens CLI will only run the free
  open-source rules available at @{<cyan;ul>https://lens.dev/r@}.

@{<ul>Commands@}:
  @{<cyan>lens login@}                Enable Pro rules, Supply Chain, and secrets scanning
  @{<cyan>lens ci@}                   Run Lens on a git diff (for use in CI)
  @{<cyan>lens scan@}                 Run Lens rules on local folders or files

@{<ul>Help@}:
  @{<cyan>lens COMMAND --help@}       For more information on each command

For the CLI docs visit @{<cyan;ul>https://lens.dev/docs/cli-reference@}
|}

(* coupling: see above *)
let print_lens_dashdash_help () =
  Ocolor_format.printf
    {|@{<ul>Usage@}: @{<cyan>lens [OPTIONS] COMMAND [ARGS]...@}

  To get started quickly, run @{<cyan>`lens scan --config auto`@}

  Run @{<cyan>`lens SUBCOMMAND --help`@} for more information on each subcommand

  If no subcommand is passed, will show a welcome message with usage info

@{<ul>Options@}:
  -h, --help  Show this message and exit.

@{<ul>Commands@}:
  @{<cyan>ci@}                   Run Lens on a git diff (for use in CI)
  @{<cyan>install-lens-pro@}  Install the Lens Pro Engine
  @{<cyan>login@}                Obtain and save credentials for @{<cyan;ul>lens.dev@}
  @{<cyan>logout@}               Remove locally stored credentials to @{<cyan;ul>lens.dev@}
  @{<cyan>lsp@}                  Start the Lens LSP server (useful for IDEs)
  @{<cyan>publish@}              Upload rule to @{<cyan;ul>lens.dev@}
  @{<cyan>scan@}                 Run Lens rules on local folders or files
  @{<cyan>show@}                 Show various types of information
  @{<cyan>test@}                 Test the rules (EXPERIMENTAL improvements over scan --test)
  @{<cyan>validate@}             Validate the rules (EXPERIMENTAL improvements over scan --validate)
  @{<cyan>mcp@}                  Start the Lens MCP server
|}
